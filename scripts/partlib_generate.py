"""Generated parts: footprints for standard packages, and symbols (standard shapes or a box).

The land patterns are KiCad's official ones (kicad-footprints, generated by KiCad from IPC-7351B), copied
here for when that library cannot be downloaded: offline the board gets the same pads as online. Pad numbers
were read from the KiCad files named next to each table on 2026-11-16; tests/test_partlib_generate.py pins them.

Used when a BOM line has no LCSC number or EasyEDA has no model. A package that is not in the table is
never guessed: package_key() returns None and the caller reports the line as missing.
Footprints are built in mm with y up (Altium axes) and written in mil, relative to the library origin.
"""
import math
import re

from partlib_convert import MM, MIN_SILK, snap_symbol

# chip body width, body height -- mm
CHIPS = {"0402": (1.0, 0.5), "0603": (1.6, 0.8), "0805": (2.0, 1.25), "1206": (3.2, 1.6)}
# chip pads per KiCad family ({R,C,L,LED,D,Fuse}_<size>Metric): pad centre offset, pad width (x), pad height (y)
_LED_PADS = {"0402": (0.485, 0.59, 0.64), "0603": (0.7875, 0.875, 0.95), "0805": (0.9375, 0.975, 1.4),
             "1206": (1.4, 1.25, 1.75)}
CHIP_PADS = {
    "R": {"0402": (0.51, 0.54, 0.64), "0603": (0.825, 0.80, 0.95), "0805": (0.9125, 1.025, 1.4), "1206": (1.4625, 1.125, 1.75)},
    "C": {"0402": (0.48, 0.56, 0.62), "0603": (0.775, 0.90, 0.95), "0805": (0.95, 1.00, 1.45), "1206": (1.475, 1.15, 1.80)},
    "L": {"0402": (0.485, 0.59, 0.64), "0603": (0.7875, 0.875, 0.95), "0805": (1.0625, 0.875, 1.2), "1206": (1.575, 1.05, 1.9)},
    "LED": _LED_PADS, "D": _LED_PADS, "Fuse": _LED_PADS}
# two-pad diodes (D_SOD-123, D_SOD-323): pad centre offset, pad w, pad h, body w, body h
DIODES = {"SOD-123": (1.65, 0.90, 1.20, 2.7, 1.6), "SOD-323": (1.05, 0.60, 0.45, 1.7, 1.25)}
# dual-row ICs (SOIC-n_3.9x..mm_P1.27mm, TSSOP-n_4.4x..mm_P0.65mm): pitch, row centre offset, pad length (x),
# pad width (y), body width, body length; TSSOP-14 has its own row and length in KiCad
DUAL = {"SOIC": (1.27, 2.475, 1.95, 0.60, 3.9, None), "TSSOP": (0.65, 2.8625, 1.475, 0.40, 4.4, None)}
DUAL_ROW = {"TSSOP-14": (2.875, 1.55)}
BODY_LEN = {("SOIC", 8): 4.9, ("SOIC", 14): 8.7, ("SOIC", 16): 9.9, ("TSSOP", 8): 3.0, ("TSSOP", 14): 5.0,
            ("TSSOP", 16): 5.0, ("TSSOP", 20): 6.5}
# SOT-23, SOT-23-5, SOT-23-6: pitch, pad column offset, pad length (x), pad width (y), body width, body length
SOT = {"SOT-23-3": (0.95, 0.9375, 1.475, 0.60, 1.3, 2.9), "SOT-23-5": (0.95, 1.1375, 1.325, 0.60, 1.6, 2.9),
       "SOT-23-6": (0.95, 1.1375, 1.325, 0.60, 1.6, 2.9)}


def package_key(pkg):
    """Canonical package name from a BOM package string, or None when it is not one we generate."""
    raw = (pkg or "").strip()
    m = re.search(r"header", raw, re.I) and re.search(r"([12])\s*x\s*(\d{1,2})", raw, re.I)
    if m:
        pitch = re.search(r"(\d\.\d+)\s*mm", raw)
        if pitch and pitch.group(1) != "2.54":
            return None
        return f"PinHeader-{m.group(1)}x{int(m.group(2)):02d}_P2.54mm"
    from library import _normalize_pkg
    s = _normalize_pkg(re.sub(r"[_\s]*\d+(\.\d+)?\s*x\s*\d+(\.\d+)?\s*mm", "", raw, flags=re.I))
    s = re.sub(r"^(c|r|l|led|d)(?=\d{4}$)", "", s)           # c0603, r0805, led0603
    if s in CHIPS:
        return s
    if s in ("sod123", "sod323"):
        return f"SOD-{s[3:]}"
    if s in ("sot23", "sot233"):
        return "SOT-23-3"
    if s in ("sot235", "sot236"):
        return f"SOT-23-{s[-1]}"
    if s == "sot223":
        return "SOT-223"
    m = re.fullmatch(r"(soic|tssop)(\d+)", s)
    if m and (m.group(1).upper(), int(m.group(2))) in BODY_LEN:
        return f"{m.group(1).upper()}-{m.group(2)}"
    return None


def _pad(num, x, y, w, h, shape=2, hole=0):
    layer, plated = ("Multi-Layer", 1) if hole else ("Top Layer", 1)
    return (f"PAD|{num}|{_m(x)}|{_m(y)}|0|{layer}|{plated}|{_m(hole) if hole else 0}|0|0|0|{_m(w)}|{_m(h)}|{shape}|")


def _m(v):
    return round(v * MM, 3) + 0.0


def _track(x1, y1, x2, y2, layer, w=MIN_SILK):
    return f"TRACK|{_m(x1)}|{_m(y1)}|{_m(x2)}|{_m(y2)}|{w}|{layer}"


def _rect(x1, y1, x2, y2, layer, w):
    return [_track(x1, y1, x2, y1, layer, w), _track(x2, y1, x2, y2, layer, w),
            _track(x2, y2, x1, y2, layer, w), _track(x1, y2, x1, y1, layer, w)]


SILK_TO_PAD = 0.15                      # mm, JLC's silkscreen-to-pad clearance
CLEAR = SILK_TO_PAD + 0.02 + MIN_SILK / MM / 2      # copper edge to the centre of a silk line, 0.02 mm to spare
DOT_R = 0.12                            # pin-1 dot radius, mm


def _finish(name, desc, pads, body, silk, pin1=None, tht=False):
    """pads: [(num,x,y,w,h[,shape,hole])] in mm; body (w,h) mm; silk: extra TRACK lines."""
    xs = [p[1] + s * p[3] / 2 for p in pads for s in (-1, 1)] + [-body[0] / 2, body[0] / 2]
    ys = [p[2] + s * p[4] / 2 for p in pads for s in (-1, 1)] + [-body[1] / 2, body[1] / 2]
    c = 0.25                                            # courtyard margin
    lines = [_pad(p[0], p[1], p[2], p[3], p[4], *p[5:7]) for p in pads]
    lines += silk
    if pin1:
        lines.append(f"ARC|{_m(pin1[0])}|{_m(pin1[1])}|{_m(DOT_R)}|0|360|{MIN_SILK}|Top Overlay")
    lines += [_track(-body[0] / 2, -body[1] / 2, body[0] / 2, -body[1] / 2, "Mechanical Layer 13", 4),
              _track(body[0] / 2, -body[1] / 2, body[0] / 2, body[1] / 2, "Mechanical Layer 13", 4),
              _track(body[0] / 2, body[1] / 2, -body[0] / 2, body[1] / 2, "Mechanical Layer 13", 4),
              _track(-body[0] / 2, body[1] / 2, -body[0] / 2, -body[1] / 2, "Mechanical Layer 13", 4)]
    x1, x2, y1, y2 = min(xs) - c, max(xs) + c, min(ys) - c, max(ys) + c
    hw = MIN_SILK / MM / 2
    marks = [(float(f[i]) / MM, float(f[i + 1]) / MM, hw) for f in (ln.split("|") for ln in silk if ln.startswith("TRACK|"))
             for i in (1, 3)] + ([(pin1[0], pin1[1], DOT_R + hw)] if pin1 else [])
    for x, y, r in marks:                               # silk kept clear of the pads may lie beyond them: still inside
        x1, x2, y1, y2 = min(x1, x - r), max(x2, x + r), min(y1, y - r), max(y2, y + r)
    lines += [_track(x1, y1, x2, y1, "Mechanical Layer 15", 2), _track(x2, y1, x2, y2, "Mechanical Layer 15", 2),
              _track(x2, y2, x1, y2, "Mechanical Layer 15", 2), _track(x1, y2, x1, y1, "Mechanical Layer 15", 2)]
    return {"name": name, "desc": desc, "lines": lines, "tht": tht, "model": None}


POLARISED = ("D", "LED", "TVS", "ZD")
# the KiCad chip family of a reference prefix (as partlib_kicad.CHIP_LIB picks the online footprint) and its name
_FAMILY = {"C": "C", "L": "L", "FB": "L", "LED": "LED", "D": "D", "TVS": "D", "ZD": "D", "F": "Fuse"}
_FAMILY_NAME = {"R": "CHIP", "C": "C-CHIP", "L": "L-CHIP", "LED": "LED-CHIP", "D": "D-CHIP", "Fuse": "F-CHIP"}


def _cathode_bar(cx, pw, y):
    """A silk bar beyond pad 1 (the cathode, as the symbol draws pin 1 and KiCad's LED/diode footprints mark it),
    its edge SILK_TO_PAD + 0.02 mm clear of the copper (CLEAR)."""
    bx = -cx - pw / 2 - CLEAR
    return _track(bx, -y, bx, y, "Top Overlay")


def footprint_for(key, prefix=None):
    """The generated footprint dict {name, lines, tht, model} for a canonical package key. A chip package takes
    the pads of its KiCad family (R by default, C, L, LED, D, Fuse by prefix), named CHIP-0805, C-CHIP-0805 ...;
    a diode or LED (prefix D, LED, TVS, ZD) also gets a cathode bar beyond pad 1."""
    desc = f"{key} KiCad library land pattern (generated)"
    if key in CHIPS:
        family = _FAMILY.get(prefix, "R")
        cx, pw, ph = CHIP_PADS[family][key]
        bw, bh = CHIPS[key]
        y = ph / 2 + CLEAR
        silk = [_track(-cx, y, cx, y, "Top Overlay"), _track(-cx, -y, cx, -y, "Top Overlay")]
        pads = [(1, -cx, 0, pw, ph), (2, cx, 0, pw, ph)]
        name = f"{_FAMILY_NAME[family]}-{key}"
        if prefix in POLARISED:
            return _finish(name, desc + ", pad 1 = cathode", pads, (bw, bh), silk + [_cathode_bar(cx, pw, y)])
        return _finish(name, desc, pads, (bw, bh), silk)
    if key in DIODES:
        cx, pw, ph, bw, bh = DIODES[key]
        y = max(max(ph, bh) / 2 + 0.2, ph / 2 + CLEAR)
        silk = [_track(-cx, y, cx, y, "Top Overlay"), _track(-cx, -y, cx, -y, "Top Overlay"), _cathode_bar(cx, pw, y)]
        return _finish(key, desc, [(1, -cx, 0, pw, ph), (2, cx, 0, pw, ph)], (bw, bh), silk)
    if key in SOT:
        pitch, cx, pw, ph, bw, bl = SOT[key]
        n = int(key[-1])
        if n == 3:
            pads = [(1, -cx, pitch, pw, ph), (2, -cx, -pitch, pw, ph), (3, cx, 0, pw, ph)]   # JEDEC TO-236: pins 1-2 are 2 pitches apart
        else:
            rows = [pitch, 0, -pitch]
            pads = [(i + 1, -cx, rows[i], pw, ph) for i in range(3)]
            right = [4, 5, 6] if n == 6 else [4, 5]
            ys = [-pitch, 0, pitch] if n == 6 else [-pitch, pitch]
            pads += [(num, cx, y, pw, ph) for num, y in zip(right, ys)]
            pads.sort(key=lambda p: p[0])
        ye = max(p[2] + p[4] / 2 for p in pads) + CLEAR
        silk = [_track(-bw / 2, ye, bw / 2, ye, "Top Overlay"), _track(-bw / 2, -ye, bw / 2, -ye, "Top Overlay")]
        return _finish(key, desc, pads, (bw, bl), silk, pin1=(-cx - pw / 2 - CLEAR - DOT_R, pads[0][2]))
    if key == "SOT-223":
        # KiCad's SOT-223-3_TabPin2: the tab is pad 2 too (the middle pin's net, as on a 3-pin LDO's symbol)
        pads = [(1, -3.15, 2.3, 2.0, 1.5), (2, -3.15, 0, 2.0, 1.5), (3, -3.15, -2.3, 2.0, 1.5), (2, 3.15, 0, 2.0, 3.8)]
        silk = [_track(-1.8, 3.35, 1.8, 3.35, "Top Overlay"), _track(-1.8, -3.35, 1.8, -3.35, "Top Overlay")]
        return _finish(key, desc, pads, (3.5, 6.5), silk, pin1=(-3.15 - 1.0 - CLEAR - DOT_R, 2.3))
    m = re.fullmatch(r"(SOIC|TSSOP)-(\d+)", key)
    if m:
        pitch, rx, pl, pw, bw, _ = DUAL[m.group(1)]
        rx, pl = DUAL_ROW.get(key, (rx, pl))
        n = int(m.group(2))
        bl = BODY_LEN[(m.group(1), n)]
        top = (n / 2 - 1) * pitch / 2
        half = n // 2
        pads = [(i + 1, -rx, top - i * pitch, pl, pw) for i in range(half)]
        pads += [(half + i + 1, rx, -top + i * pitch, pl, pw) for i in range(half)]
        ye = bl / 2
        xe = min(bw / 2, rx - pl / 2 - CLEAR)
        silk = [_track(-xe, ye, xe, ye, "Top Overlay"), _track(-xe, -ye, xe, -ye, "Top Overlay")]
        return _finish(key, desc, pads, (bw, bl), silk, pin1=(-rx - pl / 2 - CLEAR - DOT_R, top))
    m = re.fullmatch(r"PinHeader-(\d)x(\d+)_P2\.54mm", key)
    if m:
        rows, n = int(m.group(1)), int(m.group(2))
        pads = []
        for i in range(n):
            for r in range(rows):
                pads.append((i * rows + r + 1, r * 2.54, -i * 2.54, 1.7, 1.7, 2 if i == 0 and r == 0 else 1, 1.0))
        bw, bh = rows * 2.54, n * 2.54
        cx, cy = (rows - 1) * 2.54 / 2, -(n - 1) * 2.54 / 2
        for p in range(len(pads)):                                  # centre the part on the library origin
            q = list(pads[p])
            q[1] -= cx
            q[2] -= cy
            pads[p] = tuple(q)
        silk = []
        for ln in _rect(-bw / 2, -bh / 2, bw / 2, bh / 2, "Top Overlay", MIN_SILK):
            silk.append(ln)
        return _finish(key, desc, pads, (bw, bh), silk, tht=True)
    raise KeyError(key)


# ------------------------------------------------------------------ symbols
POWER_NAME = re.compile(r"^(\+?\d+V\d*|[AD]?GND\w*|VSS\w*|VCC\w*|VDD\w*|VBAT\w*|VIN\w*|VBUS\w*|VREF\w*|PGND\w*|"
                        r"\+\w+)$", re.I)
GROUND_NAME = re.compile(r"^([AD]?GND\w*|VSS\w*|PGND\w*|EP|PAD)$", re.I)
OUT_NAME = re.compile(r"(^|_)(OUT|TX|TXD|DO|SO|MOSI|Q)\d*($|_)", re.I)
IN_NAME = re.compile(r"(^|_)(IN|RX|RXD|DI|SI|MISO|EN|CLK|CS|NRST|RESET)\d*($|_)", re.I)
PASSIVE_PREFIX = {"R", "C", "L", "FB", "D", "LED", "F", "TVS", "ZD", "Y", "X", "SW", "TP", "J", "P", "JP", "RN"}


def pin_type(name, prefix):
    if prefix in PASSIVE_PREFIX:
        return "Passive"
    if POWER_NAME.match(name or ""):
        return "Power"
    if OUT_NAME.search(name or ""):
        return "Output"
    if IN_NAME.search(name or ""):
        return "Input"
    return "IO"


def _pin(num, name, ptype, orient, x, y, length):
    return {"num": str(num), "name": name, "type": ptype, "orient": orient, "x": x, "y": y, "len": length}


def two_pin_symbol(prefix, hint, pins):
    """R / C / L / diode / generic two-pin shapes. pins: [(num,name)] in order; returns (pins, gfx, issues),
    or None when the sheet's cathode is not pin 1 (the generated footprint would disagree)."""
    (n1, nm1), (n2, nm2) = (list(pins) + [("1", "1"), ("2", "2")])[:2]
    issues = []
    left, right = (n1, nm1), (n2, nm2)
    shape = "box"
    if prefix in ("D", "LED", "TVS", "ZD"):
        shape = "diode"
        # SOD/chip diode pad 1 is the cathode; sheet pin names A/K override
        role = lambda nm: {"A": "A", "AN": "A", "ANODE": "A", "+": "A", "K": "K", "C": "K", "CAT": "K", "CATHODE": "K",
                           "-": "K"}.get(nm.strip().upper(), nm.upper())
        names = {role(nm1): (n1, nm1), role(nm2): (n2, nm2)}
        if {"A", "K"} <= set(names):
            left, right = names["A"], names["K"]
            if right[0] != "1":                         # the generated footprint marks pad 1 as the cathode
                return None
        else:
            left, right = (n2, nm2), (n1, nm1)
            issues.append("unverified: pin 1 drawn as the cathode (the netlist does not name A/K); "
                          + ("LED polarity differs between makers, " if prefix == "LED" else "") + "check the datasheet")
    elif prefix in ("C",):
        shape = "cap"
    elif prefix in ("L", "FB"):
        shape = "ind"
    elif prefix == "R" or not prefix:
        shape = "box"
    pt = lambda: "Passive"
    if shape in ("box", "ind"):
        half, ln = 100, 100
    else:
        half, ln = 20, 180
    p = [_pin(left[0], left[1], pt(), "eRotate180", -half, 0, ln),
         _pin(right[0], right[1], pt(), "eRotate0", half, 0, ln)]
    if shape == "box":
        g = [["rectangle", "1", "1", "0", -100, -40, 100, 40]]
    elif shape == "cap":
        g = [["polyline", "1", "1", -20, -60, -20, 60], ["polyline", "1", "1", 20, -60, 20, 60]]
    elif shape == "ind":
        g = [["arc", "1", "1", -75 + 50 * i, 0, 25, 0, 180] for i in range(4)]
    else:
        g = [["polygon", "1", "1", "1", -20, 70, -20, -70, 20, 0], ["polyline", "1", "1", 20, -70, 20, 70]]
    return p, g, issues


def transistor_symbol(name_hint, pins):
    """3-pin Q: gate/base left, drain/collector top, source/emitter bottom. pins: [(num,name)] or []."""
    issues = []
    role, names = {}, set()
    for num, nm in pins:                  # the pin functions come only from the caller (netlist sheet), never from pad order
        u = (nm or "").upper()
        r = ("g" if u in ("G", "B", "GATE", "BASE") else "d" if u in ("D", "C", "DRAIN", "COLLECTOR")
             else "s" if u in ("S", "E", "SOURCE", "EMITTER") else "?")
        role[r] = (num, nm)
        names.add("bjt" if u in ("B", "C", "E", "BASE", "COLLECTOR", "EMITTER") else "fet" if r != "?" else "")
    if set(role) != {"g", "d", "s"} or len(names - {""}) != 1:
        return None
    bjt = "bjt" in names
    h = name_hint or ""
    if bjt:                               # polarity from the type; unknown polarity gets no arrow head
        pol = "p" if re.search(r"\bpnp\b", h, re.I) else "n" if re.search(r"\bnpn\b", h, re.I) else ""
    else:
        pol = ("p" if re.search(r"\bp[-_ ]?ch(annel)?\b|\bp-?mos(fet)?\b|\bp\b", h, re.I)
               else "n" if re.search(r"\bn[-_ ]?ch(annel)?\b|\bn-?mos(fet)?\b|\bn\b", h, re.I) else "")
    if not pol:
        issues.append(f"unverified: polarity ({'NPN or PNP' if bjt else 'N or P channel'}) not known, drawn without an "
                      "arrow; check the datasheet")
    p = [_pin(role["g"][0], role["g"][1], "Passive", "eRotate180", -100, 0, 200),
         _pin(role["d"][0], role["d"][1], "Passive", "eRotate90", 0, 100, 200),
         _pin(role["s"][0], role["s"][1], "Passive", "eRotate270", 0, -100, 200)]
    if bjt:
        g = [["polyline", "1", "1", -100, 0, -40, 0], ["polyline", "1", "1", -40, -60, -40, 60],
             ["polyline", "1", "1", -40, 20, 0, 60, 0, 100], ["polyline", "1", "1", -40, -20, 0, -60, 0, -100]]
        if pol:                           # emitter arrow: out of the base for NPN, into it for PNP
            g.append(["polygon", "1", "1", "1", -6, -54, -19, -24, -36, -41] if pol == "n" else
                     ["polygon", "1", "1", "1", -34, -26, -4, -39, -21, -56])
        return p, g, issues
    # enhancement MOSFET as drawn in datasheets: gate plate, a channel of three segments, drain and source leads,
    # the body tied to the source, its arrow pointing into the channel (N) or out of it (P)
    g = [["polyline", "1", "1", -100, 0, -45, 0], ["polyline", "1", "1", -45, -60, -45, 60],
         ["polyline", "1", "1", -30, 40, -30, 70], ["polyline", "1", "1", -30, -15, -30, 15],
         ["polyline", "1", "1", -30, -70, -30, -40],
         ["polyline", "1", "1", -30, 55, 0, 55, 0, 100], ["polyline", "1", "1", -30, -55, 0, -55, 0, -100],
         ["polyline", "1", "1", -30, 0, 0, 0, 0, -55]]
    if pol:
        g.append(["polygon", "1", "1", "1", -8, 0, -24, 10, -24, -10] if pol == "p" else
                 ["polygon", "1", "1", "1", -28, 0, -12, 10, -12, -10])
    return p, g, issues


def box_symbol(prefix, pins, issues):
    """A rectangle with the part's pins: power top, ground bottom, outputs right, the rest left.

    pins: [{"num","name","side"?}] from the netlist sheet. Names the sheet marks left/right keep that side."""
    left, right, top, bottom = [], [], [], []
    for pn in pins:
        name = pn.get("name") or ""
        side = pn.get("side")
        if GROUND_NAME.match(name):
            bottom.append(pn)
        elif POWER_NAME.match(name) and prefix not in PASSIVE_PREFIX and side not in ("left", "right"):
            top.append(pn)
        elif side == "right" or (not side and OUT_NAME.search(name)):
            right.append(pn)
        else:
            left.append(pn)
    ndots = max(len(left), len(right), 1)
    maxl = max([len(p["name"]) for p in left] or [0])
    maxr = max([len(p["name"]) for p in right] or [0])
    width = max(600, math.ceil(((maxl + maxr) * 60 + 200) / 100) * 100)
    half = max(math.ceil(width / 200) * 100, 100 * (max(len(top), len(bottom)) // 2 + 1))
    ymax, ymin = 100, -100 * ndots
    out = []

    def pin(pn, orient, x, y):
        out.append(_pin(pn["num"], pn["name"], pin_type(pn["name"], prefix), orient, x, y, 200))
    for i, pn in enumerate(left):
        pin(pn, "eRotate180", -half, -100 * i)
    for i, pn in enumerate(right):
        pin(pn, "eRotate0", half, -100 * i)
    for grp, orient, y in ((top, "eRotate90", ymax), (bottom, "eRotate270", ymin)):
        start = -100 * ((len(grp) - 1) // 2)
        for i, pn in enumerate(grp):
            pin(pn, orient, start + 100 * i, y)
    gfx = [["rectangle", "1", "1", "0", -half, ymin, half, ymax]]
    return out, gfx, issues


def symbol_for(prefix, hint, sheet_pins, npads):
    """(pins, gfx, issues) for a part, or None when its pins cannot be known (never invented).

    sheet_pins: [{"num","name","side"?}] from the project's netlist sheets (may be empty);
    npads: pad count of the footprint, used when the sheet has no pins for the part."""
    sp = [p for p in sheet_pins if re.fullmatch(r"[A-Za-z0-9]{1,6}", str(p.get("num", "")))]
    issues = [f"{len(sheet_pins) - len(sp)} netlist pin(s) without a pin number left out"] if len(sp) < len(sheet_pins) else []
    n = len(sp) or npads
    pairs = [(p["num"], p["name"]) for p in sp]
    if n == 2:
        two = two_pin_symbol(prefix, hint, pairs)
        return (two[0], two[1], two[2] + issues) if two else None
    if prefix == "Q" and n == 3:
        t = transistor_symbol(hint, pairs)
        if t:
            return t[0], t[1], t[2] + issues
    if not sp and prefix in ("J", "P", "JP", "H") and n:         # a header: its pins are just numbered
        sp = [{"num": str(i), "name": str(i)} for i in range(1, n + 1)]
    return box_symbol(prefix, sp, issues) if sp else None
